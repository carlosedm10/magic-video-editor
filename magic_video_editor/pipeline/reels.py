"""Stage 7 — Reels: propose ~20 short-form candidates from the kept content,
scored by the local LLM on the transcript (hook / clarity / payoff). Rendering
a candidate crops to 9:16 centered on the speaker's face and burns subtitles
built from whisper word timestamps.

Reel Editor overrides (spec v5): each reel may carry in_override/out_override
(clip-local seconds, may extend beyond the AI window, clamped to clip
bounds), crop_x (0..1 horizontal center, bypasses face detection),
cue_overrides ({cue_index: text}), subtitle_style (partial override merged
over project["subtitles"]), and editable title/description.

Multi-segment reels (spec v5.8b "the podcast case"): a reel is no longer
always a single continuous window. reel["segments"] = [{clip_id, start, end,
in_override, out_override}] (same override shape as before, now per segment)
and reel["transitions"] = junction transitions between consecutive segments
(one fewer than len(segments), default crossfade 0.4s). A pre-v5.8b
single-window reel is migrated to a 1-segment list (with no transitions) the
first time `ensure_segments` sees it (called from render_reel and from
api/reels.py). The legacy top-level clip_id/start/end/in_override/
out_override fields are kept in sync with segment 0 by `_sync_legacy_fields`
so the current (single-window) Reel Editor frontend keeps working unmodified
-- it only ever reads/writes segment 0 until it grows multi-segment UI.
cue_overrides indices are GLOBAL across the reel's segments concatenated in
order (index 0 is the first cue of segment 0, continuing into segment 1,
...), both for the /cues endpoint and for render_reel's per-segment .ass
burn-in (see `_segment_cue_overrides`). crop_x/face-detection is resolved
ONCE (from segment 0, unless crop_x is set) and reused for every segment's
crop filter -- only the per-clip pixel geometry differs (spec: "face-crop
computed on the FIRST segment unless crop_x set").

Viral composer pass (spec v5.8b "the podcast case"): after the single-window
reel_scorer pass, `_run_composer_pass` looks for PAIRS of high-scoring
windows that continue the same idea apart in time (setup+payoff,
question+answer, ...) among the top ~15 scored windows, pre-filtered by
rapidfuzz keyword overlap and capped at ~10 agent calls (task
'reel_composer'). A pair the agent says to `combine` becomes a 2-segment
candidate with a +2 score bonus, entering the same top-N / overlap-limited
pick loop as single-window candidates (see `_windows_of`/`_overlap`, which
treat both uniformly); reels built from a combined pair are flagged
reel["composed"] = True with reel["composer_why"] set to the agent's
rationale.

Render (reels.render_reel): reuses render.py's per-segment encode
(`render._encode_segment`) and junction crossfade merge
(`render._merge_crossfades`) rather than reimplementing them -- see that
module's docstring for the junction algorithm. Each segment is cut/cropped/
subtitled independently (crop/subs/overrides apply per segment; face-crop
computed once as above), then junctions are merged exactly like the main
render, then concatenated.

Export naming (spec v5 addendum): rendered reels are written straight to
settings.export_dir/<project name>/<sanitized reel title>.mp4 (falling back
to "Reel <rank>" when there's no title yet), deduped against what's already
there ("<stem> (2).mp4", ...). Internal work files (the per-reel .ass/.wav
under <project>/work) keep using the reel id; only the final artifact adopts
the title-based name, and reel["path"] is updated to point at it.

Copywriter integration (spec v5 addendum): after picking the top N, each
reel's title/description/hashtags are generated by the COPYWRITER agent
(magic_video_editor/pipeline/copywriter.py, a parallel deliverable) via copy_for_reel —
imported lazily so this module works whether or not that file has landed
yet. On success it replaces reel_scorer's title; on failure/absence the
scorer's title is kept as a fallback."""

